oc$G <- factor(oc$G, levels = names(G_library))
write.csv(oc, "results/tables/operating_characteristics_all.csv", row.names = FALSE)

rule_levels <- c("oracle:threshold", "oracle:stepup", "npmle:threshold", "npmle:stepup",
                 "betabinom:threshold", "betabinom:stepup", "unpooled:threshold",
                 "binom_test:BH", "binom_test:BY", "robust_box:threshold", "robust_box:stepup")
rule_labels <- c("Oracle lfdr <= q (benchmark)", "Oracle step-up", "NPMLE lfdr <= q",
                 "NPMLE step-up", "Beta-binomial EB lfdr <= q", "Beta-binomial step-up",
                 "Unpooled Beta(1,1) <= q", "Exact test + BH", "Exact test + BY",
                 "Box-robust U <= q/2 (FDR <= q)", "Box-robust step-up")
palette <- c("Oracle lfdr <= q (benchmark)" = "#52514e", "NPMLE lfdr <= q" = "#2a78d6",
             "Beta-binomial EB lfdr <= q" = "#eb6834", "Unpooled Beta(1,1) <= q" = "#1baf7a",
             "Exact test + BH" = "#eda100", "Exact test + BY" = "#e87ba4",
             "Box-robust U <= q/2 (FDR <= q)" = "#6250d6")
shapes <- c(16, 15, 17, 18, 4, 3, 8); names(shapes) <- names(palette)
main_rules <- rule_levels[c(1, 3, 5, 7, 8, 10)]
lab_rule <- function(x) factor(rule_labels[match(x, rule_levels)], levels = rule_labels)
oc$method <- lab_rule(oc$rule)
theme_set(theme_minimal(base_size = 10) +
            theme(panel.grid.minor = element_blank(), legend.position = "bottom",
                  plot.caption = element_text(hjust = 0, size = 8), plot.title.position = "plot"))
G_lab <- setNames(vapply(G_library, `[[`, "", "label"), names(G_library))
save_fig <- function(p, name, w = 9, h = 6) {
  if (!nrow(p$data)) return(message("No data for ", name, "; skipped"))
  ggsave(file.path("results/figures", name), p, width = w, height = h, dpi = 150, bg = "white")
}
fmt <- function(m, s, d = 3) ifelse(is.na(m), "NA", sprintf(paste0("%.", d, "f (%.", d, "f)"), m, s))
md <- c("# Simulation results (auto-generated)", "",
        sprintf("Generated by `scripts/05_figures_tables.R`. %d scenarios x %d replicates. Entries are mean (Monte Carlo SE).",
                sum(ok), sim$nrep),
        "tau = reliability threshold; q = decision threshold (lfdr cutoff, or BH/BY level).", "")
add_table <- function(title, df, note = NULL) {
  md <<- c(md, paste("##", title), "", if (!is.null(note)) c(note, ""),
           knitr::kable(df, format = "pipe", row.names = FALSE), "")
}

