# Build tables (CSV + results/summary.md) and figures from the saved results.
source("R/load.R")
suppressPackageStartupMessages(library(ggplot2))
dir.create("results/figures", recursive = TRUE, showWarnings = FALSE)
sim <- readRDS(Sys.getenv("SIM_RESULTS", "results/sim_results.rds"))
ok <- vapply(sim$results, function(r) is.null(r$error), logical(1))
res <- sim$results[ok]
cat(sprintf("Using %d of %d scenarios (nrep = %d)\n", sum(ok), length(ok), sim$nrep))

scen_df <- function(r) as.data.frame(r$scenario[c("id", "G", "k", "J", "dependence")])
oc <- do.call(rbind, lapply(res, function(r) cbind(scen_df(r), r$oc)))
