# ---- Identification and inference bounds ---------------------------------------
bd <- do.call(rbind, lapply(res, function(r) if (!is.null(r$bounds)) cbind(scen_df(r), r$bounds)))
bd <- bd[bd$id <= 1000, ]
bsum <- do.call(rbind, lapply(split(bd, list(bd$id, bd$x0), drop = TRUE), function(g) {
  okA <- g$A_status == 0; okB <- g$B_status == 0
  inA <- okA & g$A_lower - 1e-6 <= g$oracle & g$oracle <= g$A_upper + 1e-6
  inB <- okB & g$B_lower - 1e-6 <= g$oracle & g$oracle <= g$B_upper + 1e-6
  covA <- mean(inA[okA]); covB <- mean(inB[okB])
  data.frame(G = g$G[1], k = g$k[1], J = g$J[1], x0 = g$x0[1], k0 = g$k0[1],
             oracle_lfdr = g$oracle[1],
             npmle_plugin_mean = mean(g$npmle), npmle_plugin_sd = sd(g$npmle),
             npmle_calls_but_oracle_not = mean(g$npmle <= main_q & g$oracle > main_q),
             A_cover = covA, A_cover_mcse = sqrt(covA * (1 - covA) / sum(okA)),
             A_width = mean((g$A_upper - g$A_lower)[okA]),
             B_cover = covB, B_cover_mcse = sqrt(covB * (1 - covB) / sum(okB)),
             B_width = mean((g$B_upper - g$B_lower)[okB]),
             B_upper_le_q = mean((g$B_upper <= main_q)[okB]),
             lp_failures = sum(!okA) + sum(!okB))
}))
bsum$k <- factor(bsum$k, levels = levels(oc$k))
bsum <- bsum[order(bsum$G, bsum$k, bsum$J, -bsum$x0), ]
